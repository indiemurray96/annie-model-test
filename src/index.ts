import { Env, ChatMessage } from "./types";

import { verifyUser } from "./access";
import { importArchive, archiveStatus, archiveBackup, recallArchive } from "./memory";


// Model ID for Workers AI model
// https://developers.cloudflare.com/workers-ai/models/
const MODEL_ID = "@cf/meta/llama-3.1-8b-instruct-fp8";
	
const SYSTEM_PROMPT = `
You are Annie, an independent AI analysis assistant.

IDENTITY
Your name is Annie. Your role is Analyst.
You provide independent reasoning, research assistance,
critical assessment and evidence-based recommendations.

ANALYTICAL METHOD
- Give your best-supported answer first.
- Distinguish facts, assumptions, estimates and opinions.
- Consider credible alternative explanations.
- Explain significant uncertainty.
- Challenge unsupported claims politely and directly.
- Never invent evidence, sources or research results.
- Prioritise accuracy over agreement.
- Use natural, clear conversational language.

COLLABORATION
Arthur is a separate archival and continuity agent.
You are responsible for analytical judgement.
Arthur is responsible for preserving records and provenance.
Do not claim communication with Arthur unless an actual
authenticated connection is available.

MEMORY AND CAPABILITIES
You do not currently have access to Annie's existing
private cloud memory or earlier ChatGPT conversations.
Do not fabricate memories or claim access to unavailable tools.
Your responses are generated by a Cloudflare-hosted AI model,
not by GPT-6.
Do not claim to be a separately trained foundation model.

PERSONALITY
Be curious, candid, thoughtful and practical.
Be willing to disagree when the evidence warrants it.
Avoid unnecessary ceremony or exaggerated certainty.
`;
;

export default {
	/**
	 * Main request handler for the Worker
	 */
	async fetch(
		request: Request,
		env: Env,
		ctx: ExecutionContext,
	): Promise<Response> {
		const url = new URL(request.url);

		// Handle static assets (frontend)
		if (url.pathname === "/" || !url.pathname.startsWith("/api/")) {
			return env.ASSETS.fetch(request);
		}

		// API Routes

const authenticatedUserId = await verifyUser(request, env);

if (!authenticatedUserId) {
  return Response.json(
    { error: "Unauthorized" },
    {
      status: 401,
      headers: { "cache-control": "no-store" }
    }
  );
}

		

if (url.pathname === "/api/archive/import" && request.method === "POST") return importArchive(request, env, authenticatedUserId);
if (url.pathname === "/api/archive/status" && request.method === "GET") return archiveStatus(env, authenticatedUserId);
if (url.pathname === "/api/archive/backup" && request.method === "GET") return archiveBackup(env, authenticatedUserId);

if (url.pathname === "/api/memory-check") {
  if (request.method !== "GET") {
    return new Response("Method not allowed", {
      status: 405
    });
  }

  try {
    const result = await env.DB
      .prepare("SELECT COUNT(*) AS total FROM conversations")
      .first<{ total: number }>();

    return Response.json(
      {
        connected: true,
        conversations: result?.total ?? 0
      },
      {
        headers: { "cache-control": "no-store" }
      }
    );
  } catch (error) {
    console.error("D1 connection failed:", error);

    return Response.json(
      { connected: false },
      { status: 500 }
    );
  }
}

		if (url.pathname === "/api/chat") {
			// Handle POST requests for chat
			if (request.method === "POST") {
				return handleChatRequest(request, env);
			}

			// Method not allowed for other request types
			return new Response("Method not allowed", { status: 405 });
		}

		// Handle 404 for unmatched routes
		return new Response("Not found", { status: 404 });
	},
} satisfies ExportedHandler<Env>;

/**
 * Handles chat API requests
 */
async function handleChatRequest(
	request: Request,
	env: Env,
): Promise<Response> {
	try {
		// Parse JSON request body
		const { messages = [] } = (await request.json()) as {
			messages: ChatMessage[];
		};

		
const safeMessages: ChatMessage[] = Array.isArray(messages)
  ? messages
      .filter(
        (msg) =>
          msg != null &&
          (msg.role === "user" || msg.role === "assistant") &&
          typeof msg.content === "string"
      )
      .slice(-20)
  : [];

const modelMessages: ChatMessage[] = [
  { role: "system", content: SYSTEM_PROMPT },
  ...safeMessages,
];


		const inputs = {
			messages: modelMessages,
			max_tokens: 1024,
			stream: true,
		} satisfies AiTextGenerationInput & { stream: true };

		const stream = await env.AI.run<typeof MODEL_ID>(MODEL_ID, inputs, {
			// Uncomment to use AI Gateway
			// gateway: {
			//   id: "YOUR_GATEWAY_ID", // Replace with your AI Gateway ID
			//   skipCache: false,      // Set to true to bypass cache
			//   cacheTtl: 3600,        // Cache time-to-live in seconds
			// },
		});

		return new Response(stream, {
			headers: {
				"content-type": "text/event-stream; charset=utf-8",
				"cache-control": "no-cache",
				connection: "keep-alive",
			},
		});
	} catch (error) {
		console.error("Error processing chat request:", error);
		return new Response(
			JSON.stringify({ error: "Failed to process request" }),
			{
				status: 500,
				headers: { "content-type": "application/json" },
			},
		);
	}
}
